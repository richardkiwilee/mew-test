# -*- coding: utf-8 -*-
"""反射代码生成器：schema.py -> src/generated/reflection_gen.h / .cpp

用法:  python generate.py [--out <dir>]
默认输出到 ../../src/generated（相对本文件）。

生成内容：
- 枚举声明（C++ 唯一来源）
- to_string / enum_desc / parse_enum / enum_count / enum_entries 反射 API
- 内容不变时不动输出文件（避免触发无谓重编译）
"""

from __future__ import annotations

import argparse
import os
import sys

import schema as S

HEADER_GUARD = "MEW_COMBAT_REFLECTION_GEN_H"


def _enum_decls() -> str:
    lines = []
    for e in S.ALL_ENUMS:
        lines.append(f"// {e.doc}")
        lines.append(f"enum class {e.cpp_name} : uint32_t {{")
        for i, (name, desc) in enumerate(e.entries):
            lines.append(f"    {name} = {e.value_of(i)},  // {desc}")
        lines.append("    kCount,")
        lines.append("};")
        lines.append("")
    return "\n".join(lines)


def _reflection_decls() -> str:
    lines = []
    for e in S.ALL_ENUMS:
        n = e.cpp_name
        lines.append(f"// ---- {n} ----")
        lines.append(f"constexpr uint32_t enum_count({n}) noexcept {{ return {len(e.entries)}; }}")
        lines.append(f"constexpr std::string_view enum_type_name({n}) noexcept {{ return \"{n}\"; }}")
        lines.append(f"std::string_view to_string({n} value) noexcept;")
        lines.append(f"const char* enum_desc({n} value) noexcept;")
        lines.append(f"bool parse_enum(std::string_view text, {n}& out) noexcept;")
        lines.append(f"const std::array<EnumEntry<{n}>, {len(e.entries)}>& enum_entries({n}) noexcept;")
        lines.append("")
    return "\n".join(lines)


def gen_header() -> str:
    parts = [
        "// AUTO-GENERATED by tools/codegen/generate.py — DO NOT EDIT.",
        "// Single source of truth: tools/codegen/schema.py",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace mew::combat {",
        "",
        "template <typename E>",
        "struct EnumEntry {",
        "    E value;",
        "    std::string_view name;",
        "    std::string_view desc;",
        "};",
        "",
        _enum_decls(),
        _reflection_decls(),
        "}  // namespace mew::combat",
        "",
    ]
    return "\n".join(parts)


def _entry_table(e: S.EnumDef) -> str:
    n = e.cpp_name
    lines = [
        f"const std::array<EnumEntry<{n}>, {len(e.entries)}>& enum_entries({n}) noexcept {{",
        f"    static const std::array<EnumEntry<{n}>, {len(e.entries)}> entries = {{{{",
    ]
    for i, (name, desc) in enumerate(e.entries):
        lines.append(f"        {{{n}::{name}, \"{name}\", \"{desc}\"}},")
    lines.append("    }};")
    lines.append("    return entries;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _to_string_fn(e: S.EnumDef) -> str:
    n = e.cpp_name
    lines = [
        f"std::string_view to_string({n} value) noexcept {{",
        "    switch (value) {",
    ]
    for name, _ in e.entries:
        lines.append(f"        case {n}::{name}: return \"{name}\";")
    lines.append("        default: return \"INVALID\";")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _desc_fn(e: S.EnumDef) -> str:
    n = e.cpp_name
    lines = [
        f"const char* enum_desc({n} value) noexcept {{",
        "    switch (value) {",
    ]
    for name, desc in e.entries:
        lines.append(f'        case {n}::{name}: return "{desc}";')
    lines.append('        default: return "?";')
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _parse_fn(e: S.EnumDef) -> str:
    n = e.cpp_name
    lines = [
        f"bool parse_enum(std::string_view text, {n}& out) noexcept {{",
        f"    for (const auto& entry : enum_entries({n}{{}})) {{",
        "        if (entry.name == text) {",
        "            out = entry.value;",
        "            return true;",
        "        }",
        "    }",
        "    return false;",
        "}",
        "",
    ]
    return "\n".join(lines)


def gen_cpp() -> str:
    parts = [
        "// AUTO-GENERATED by tools/codegen/generate.py — DO NOT EDIT.",
        "// Single source of truth: tools/codegen/schema.py",
        '#include "generated/reflection_gen.h"',
        "",
        "namespace mew::combat {",
        "",
    ]
    for e in S.ALL_ENUMS:
        parts.append(_entry_table(e))
        parts.append(_to_string_fn(e))
        parts.append(_desc_fn(e))
        parts.append(_parse_fn(e))
    parts.append("}  // namespace mew::combat")
    parts.append("")
    return "\n".join(parts)


def _write_if_changed(path: str, content: str) -> bool:
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            if f.read() == content:
                return False
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print(f"[codegen] wrote {path}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate C++ enum reflection")
    parser.add_argument(
        "--out",
        default=os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "..", "src", "generated")),
        help="output directory",
    )
    args = parser.parse_args()
    os.makedirs(args.out, exist_ok=True)
    header = gen_header()
    cpp = gen_cpp()
    _write_if_changed(os.path.join(args.out, "reflection_gen.h"), header)
    _write_if_changed(os.path.join(args.out, "reflection_gen.cpp"), cpp)
    print(f"[codegen] {len(S.ALL_ENUMS)} enums generated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
